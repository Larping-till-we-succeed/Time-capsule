package dev.timecapsule.app.core.rust

import dev.timecapsule.app.data.model.Project
import dev.timecapsule.app.data.model.ProjectId
import dev.timecapsule.app.data.model.ProjectStatistics
import dev.timecapsule.app.data.model.Snapshot
import dev.timecapsule.app.data.model.SnapshotDiff
import dev.timecapsule.app.data.model.SnapshotId

/**
 * Proposed Kotlin-facing contract for the shared Rust core.
 *
 * **This API does not exist yet.** The Rust engine in `src/` exposes no stable FFI surface, so
 * nothing here is implemented by native code and no `System.loadLibrary` call is made. This
 * interface exists so the boundary is written down before the Rust side commits to it, and so
 * a future UniFFI adapter can be dropped in without touching the UI.
 *
 * A future implementation (generated by UniFFI, then wrapped) implements this interface and
 * also implements `TimeCapsuleRepository`, which is the interface the UI talks to.
 *
 * See `docs/android-rust-api.md` for the full contract, type mapping and unresolved questions.
 */
interface TimeCapsuleCore {

    /** @return every project the core knows about. */
    suspend fun listProjects(): List<Project>

    /**
     * Registers a project backed by a directory the user picked through SAF.
     *
     * [directoryUri] is a `content://` tree URI. The Android adapter — not the core — is
     * responsible for resolving it into readable content; see [ProjectStorageGateway].
     */
    suspend fun createProject(name: String, directoryUri: String): Project

    suspend fun listSnapshots(projectId: ProjectId): List<Snapshot>

    /**
     * Captures a new snapshot.
     *
     * @param title short human-readable label.
     * @param note optional longer description.
     */
    suspend fun createSnapshot(projectId: ProjectId, title: String, note: String): Snapshot

    /**
     * Diffs two snapshots belonging to the same project.
     *
     * [firstSnapshotId] is the baseline, [secondSnapshotId] the snapshot compared against it.
     */
    suspend fun compareSnapshots(
        projectId: ProjectId,
        firstSnapshotId: SnapshotId,
        secondSnapshotId: SnapshotId,
    ): SnapshotDiff

    /** Restores the project directory to the state captured by [snapshotId]. */
    suspend fun restoreSnapshot(projectId: ProjectId, snapshotId: SnapshotId)

    suspend fun getProjectStatistics(projectId: ProjectId): ProjectStatistics
}

/**
 * Byte-level bridge between Android's scoped storage and the core.
 *
 * The Rust core cannot open `content://` URIs itself, so the adapter uses this gateway to
 * enumerate and read documents and to hand content to the core. Not implemented yet: the
 * gateway's contract is documented so the SAF layer and the future UniFFI adapter agree on
 * who owns what.
 */
interface ProjectStorageGateway {
    /** Human-readable description of a granted tree, used to confirm a directory selection. */
    suspend fun describe(directoryUri: String): DirectoryDescription

    /** Relative paths of the immediate children of a granted tree, for diagnostics only. */
    suspend fun listTopLevelEntries(directoryUri: String): List<String>
}

data class DirectoryDescription(
    val displayName: String,
    val entryCount: Int,
    val canRead: Boolean,
    val canWrite: Boolean,
) {
    val isUsable: Boolean get() = canRead && canWrite
}

/** Whether a native core is available in this build. */
sealed interface CoreAvailability {
    /** No UniFFI bindings are compiled into the app. This is the current, expected state. */
    data object NotIntegrated : CoreAvailability

    data class Available(val version: String) : CoreAvailability

    data class Failed(val reason: String) : CoreAvailability
}

/** Thrown when an operation needs the Rust core and no implementation is linked in. */
class CoreNotIntegratedException(operation: String) : IllegalStateException(
    "The Rust core is not integrated in this build; '$operation' cannot run.",
)

/**
 * Explicit stand-in used by the app while Rust integration is pending.
 *
 * It fails loudly instead of returning fake native results, so no screen can accidentally
 * present invented data as if the engine had produced it.
 */
object NotIntegratedTimeCapsuleCore : TimeCapsuleCore {

    override suspend fun listProjects(): List<Project> = unavailable("listProjects")

    override suspend fun createProject(name: String, directoryUri: String): Project =
        unavailable("createProject")

    override suspend fun listSnapshots(projectId: ProjectId): List<Snapshot> =
        unavailable("listSnapshots")

    override suspend fun createSnapshot(projectId: ProjectId, title: String, note: String): Snapshot =
        unavailable("createSnapshot")

    override suspend fun compareSnapshots(
        projectId: ProjectId,
        firstSnapshotId: SnapshotId,
        secondSnapshotId: SnapshotId,
    ): SnapshotDiff = unavailable("compareSnapshots")

    override suspend fun restoreSnapshot(projectId: ProjectId, snapshotId: SnapshotId): Unit =
        unavailable("restoreSnapshot")

    override suspend fun getProjectStatistics(projectId: ProjectId): ProjectStatistics =
        unavailable("getProjectStatistics")

    private fun unavailable(operation: String): Nothing =
        throw CoreNotIntegratedException(operation)
}
